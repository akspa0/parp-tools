#!/usr/bin/env pwsh
<#
.SYNOPSIS
    Regenerates docs/WoWViewer/UI-REFERENCE.md from the UI control registry.

.DESCRIPTION
    The registry (wow-viewer/eng/ui/ui-controls.json) is the source of truth. This
    script renders the generated reference and, by default, fails when the committed
    document differs from the rendered output. Pass -Write to update the document.

.EXAMPLE
    pwsh -NoProfile -File wow-viewer/eng/ui/Update-UiReference.ps1
    pwsh -NoProfile -File wow-viewer/eng/ui/Update-UiReference.ps1 -Write
#>
[CmdletBinding()]
param(
    [switch] $Write,
    [string] $RepositoryRoot = (Resolve-Path (Join-Path $PSScriptRoot '..\..\..')).Path
)

$ErrorActionPreference = 'Stop'

$registryPath = Join-Path $RepositoryRoot 'wow-viewer/eng/ui/ui-controls.json'
$documentPath = Join-Path $RepositoryRoot 'wow-viewer/docs/WoWViewer/UI-REFERENCE.md'

if (-not (Test-Path -LiteralPath $registryPath)) { throw "Missing UI control registry: $registryPath" }

$registry = Get-Content -LiteralPath $registryPath -Raw | ConvertFrom-Json
$controls = @($registry.controls | Sort-Object region, label)

$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('# UI Reference')
$lines.Add('')
$lines.Add('Generated from `wow-viewer/eng/ui/ui-controls.json`. Do not edit this file by hand:')
$lines.Add('run `wow-viewer/eng/ui/Update-UiReference.ps1` and the build check fails on drift.')
$lines.Add('')
$lines.Add(('Controls documented: **{0}**' -f $controls.Count))
$lines.Add('')

$currentRegion = $null
foreach ($control in $controls)
{
    if (-not $control.visible) { continue }
    if ($control.region -ne $currentRegion)
    {
        $currentRegion = $control.region
        $lines.Add(('## {0}' -f $currentRegion))
        $lines.Add('')
        $lines.Add('| Control | Shortcut | Description |')
        $lines.Add('|---|---|---|')
    }

    $shortcut = if ([string]::IsNullOrWhiteSpace($control.shortcut)) { '-' } else { ('`' + $control.shortcut + '`') }
    $lines.Add(('| {0} | {1} | {2} |' -f $control.label, $shortcut, $control.help))
}
$lines.Add('')

$rendered = ($lines -join "`n")

if ($Write)
{
    $documentDirectory = Split-Path -Parent $documentPath
    if (-not (Test-Path -LiteralPath $documentDirectory)) { New-Item -ItemType Directory -Force -Path $documentDirectory | Out-Null }
    Set-Content -LiteralPath $documentPath -Value $rendered -Encoding utf8 -NoNewline
    Write-Output ("Wrote {0}" -f $documentPath)
    exit 0
}

if (-not (Test-Path -LiteralPath $documentPath))
{
    Write-Error ("UI reference is missing: {0}. Run this script with -Write." -f $documentPath)
    exit 1
}

$committed = (Get-Content -LiteralPath $documentPath -Raw).Replace("`r`n", "`n")
if ($committed -ne $rendered)
{
    Write-Error "UI reference is out of date. Run: pwsh -NoProfile -File wow-viewer/eng/ui/Update-UiReference.ps1 -Write"
    exit 1
}

Write-Output ("UI reference is up to date ({0} controls)." -f $controls.Count)
